#!/usr/bin/env python3
"""Offline timing/source shadow of HostRatePolicy over a recorded reference run.

No transport/device is opened. The recorded trajectory was generated by the MCU
reference controller. Shadow outputs cannot establish counterfactual closed-loop
performance, hardware latency or physical acceptance.
"""
import argparse
from dataclasses import asdict
import gzip
from hashlib import sha256
import json
from pathlib import Path
import statistics
from cartpole_sdk.contracts import Channel, Observation, Sample
from cartpole_sdk.recording import _session, strict_json_loads
from cartpole_sdk.policies import HostRatePolicy


def observation(session,state):
    # Match the documented Rig._observation field/source/clock mapping without
    # constructing or importing a Rig/operator object.
    t=state['unwrapped_us']*1000
    specs=(('cart','position','step','x','m','cart-step-home','step_count','estimated',bool(state['flags']&4)),
           ('cart','velocity','step','velocity','m/s','cart-step-home','commanded_velocity','estimated',True),
           ('pole','angle','magnetic','theta','rad','encoder-zero','magnetic_decoded','measured',bool(state['flags']&1)),
           ('pole','angular_velocity','magnetic','omega','rad/s','encoder-zero','filtered_magnetic_rate','estimated',bool(state['flags']&1)))
    samples=tuple(Sample(entity,quantity,source,state[field] if valid else None,unit,frame,
        method,'valid' if valid else 'invalid',None if valid else 'recorded sensor/reference invalid',
        kind,t,t,t) for entity,quantity,source,field,unit,frame,method,kind,valid in specs)
    return Observation(session.session_id,session.clock_id,state['unwrapped_tick'],t,
                       'board acquisition snapshot proxy',samples)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('recording',type=Path)
    parser.add_argument('--rate',type=int,choices=(100,250),default=250)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    opener=gzip.open if args.recording.suffix=='.gz' else open
    with opener(args.recording,'rt') as stream:rows=[strict_json_loads(line) for line in stream]
    header=next(row for row in rows if row['type']=='session')
    session=_session(header['session'])
    states=[row['state'] for row in rows if row['type']=='state']
    active=[i for i,state in enumerate(states) if state['mode'] in (2,3)]
    if not active:raise ValueError('recording has no MCU reference-controller interval')
    # Include every state within this interval, not just healthy ones or exact
    # cadence states; bad/intervening data must remain visible to the policy.
    states=states[min(active):max(active)+1]
    if any(str(s['sid'])!=session.session_id for s in states):raise ValueError('recording crosses sessions')
    first=observation(session,states[0])
    channels=tuple(s.channel for s in first.samples)
    policy=HostRatePolicy(channels,rate_hz=args.rate);policy.reset(session)
    outputs=[];first_fault=None
    for i,state in enumerate(states):
        intent=policy.act(observation(session,state))
        if intent is None:
            if first_fault is None:first_fault=dict(index=i,tick=state['unwrapped_tick'],reason=policy.fault_reason)
        else:outputs.append(intent.acceleration_m_s2)
    board=[b['unwrapped_us']-a['unwrapped_us'] for a,b in zip(states,states[1:])]
    host=[(b['received_ns']-a['received_ns'])/1e6 for a,b in zip(states,states[1:])]
    result=dict(mode='offline shadow only; recorded MCU reference trajectory',
        physical_acceptance=False,counterfactual_control_quality_assessed=False,
        input_path=str(args.recording),input_sha256=sha256(args.recording.read_bytes()).hexdigest(),
        policy_source_sha256=sha256((Path(__file__).resolve().parents[1]/'src/cartpole_sdk/policies/host.py').read_bytes()).hexdigest(),
        shadow_source_sha256=sha256(Path(__file__).read_bytes()).hexdigest(),
        rate_hz=args.rate,channels=[asdict(c) for c in channels],session=asdict(session),
        selection='all recorded states from first through last MCU mode2/3 inclusive; no resampling/filtering/reset after faults',
        states=len(states),intents=len(outputs),first_fault=first_fault,
        board_duration_s=(states[-1]['unwrapped_us']-states[0]['unwrapped_us'])/1e6,
        board_interval_us=dict(min=min(board),max=max(board),median=statistics.median(board)),
        host_receipt_interval_ms=dict(min=min(host),max=max(host),median=statistics.median(host)),
        max_abs_shadow_raw_acceleration_m_s2=max(map(abs,outputs),default=0.),
        saturated_intents=sum(abs(value)>=25 for value in outputs),
        notes=['Effective/available board timestamps retain the SDK acquisition-snapshot proxy; they do not measure sensor filter or USB latency.',
               'Magnetic angle is decoded; magnetic angular velocity is the recorded MCU filtered estimate.',
               'Cart position and velocity are step/command estimates, not independent physical travel measurements.',
               'Only timing/source compatibility is tested. No shadow output was sent to hardware.'])
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(result,indent=2,sort_keys=True,allow_nan=False)+'\n')
    print(json.dumps({k:result[k] for k in ('states','intents','first_fault','board_interval_us','max_abs_shadow_raw_acceleration_m_s2')},sort_keys=True))


if __name__=='__main__':main()
